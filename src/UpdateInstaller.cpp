struct InternetHandle {
    HINTERNET value;
    explicit InternetHandle(HINTERNET handle) : value(handle) {}
    ~InternetHandle() { if (value) InternetCloseHandle(value); }
    InternetHandle(const InternetHandle &) = delete;
    InternetHandle &operator=(const InternetHandle &) = delete;
};

class Sha256 {
public:
    Sha256() {
        if (BCryptOpenAlgorithmProvider(&provider, BCRYPT_SHA256_ALGORITHM, nullptr, 0) >= 0)
            BCryptCreateHash(provider, &hash, nullptr, 0, nullptr, 0, 0);
    }
    ~Sha256() {
        if (hash) BCryptDestroyHash(hash);
        if (provider) BCryptCloseAlgorithmProvider(provider, 0);
    }
    bool append(BYTE *bytes, DWORD count) {
        return hash && BCryptHashData(hash, bytes, count, 0) >= 0;
    }
    std::string finish() {
        BYTE digest[32];
        if (!hash || BCryptFinishHash(hash, digest, sizeof(digest), 0) < 0) return {};
        const char hex[] = "0123456789abcdef";
        std::string text;
        for (BYTE byte : digest) { text += hex[byte >> 4]; text += hex[byte & 15]; }
        return text;
    }
    Sha256(const Sha256 &) = delete;
    Sha256 &operator=(const Sha256 &) = delete;
private:
    BCRYPT_ALG_HANDLE provider = nullptr;
    BCRYPT_HASH_HANDLE hash = nullptr;
};

std::wstring modulePath() {
    std::wstring path(32768, L'\0');
    DWORD length = GetModuleFileNameW(nullptr, &path[0], static_cast<DWORD>(path.size()));
    if (!length || length >= path.size()) return {};
    path.resize(length);
    return path;
}

// All substituted arguments are paths or numeric values generated by this module.
std::wstring quoted(const std::wstring &value) { return L"\"" + value + L"\""; }

struct UpdateJob {
    explicit UpdateJob(bool installing) : download(installing) {}
    ~UpdateJob() {
        if (!handedOff) {
            if (!installer.empty()) DeleteFileW(installer.c_str());
            if (!relay.empty()) DeleteFileW(relay.c_str());
            if (!directory.empty()) RemoveDirectoryW(directory.c_str());
        }
    }
    const bool download;
    std::atomic_bool cancel{false}, done{false};
    std::atomic<uint64_t> received{0};
    UpdateInfo info;
    DWORD error = ERROR_SUCCESS;
    CHandle gate;
    std::wstring directory, installer, relay, target;
    bool handedOff = false;
};

DWORD downloadInstaller(UpdateJob &job) {
    wchar_t temp[32768];
    DWORD length = GetTempPathW(ARRAYSIZE(temp), temp);
    if (!length || length >= ARRAYSIZE(temp)) return ERROR_PATH_NOT_FOUND;
    GUID guid;
    wchar_t id[40];
    if (FAILED(CoCreateGuid(&guid)) || !StringFromGUID2(guid, id, ARRAYSIZE(id)))
        return ERROR_GEN_FAILURE;
    job.directory = std::wstring(temp) + L"FileSpacerUpdate-" + id;
    if (!CreateDirectoryW(job.directory.c_str(), nullptr)) return GetLastError();
    job.installer = job.directory + L"\\FileSpacer-install.exe";
    job.relay = job.directory + L"\\FileSpacerUpdate.exe";
    job.target = modulePath();
    if (job.target.empty()) return ERROR_PATH_NOT_FOUND;
    // The relay must not keep the installed executable mapped during installation.
    if (!CopyFileW(job.target.c_str(), job.relay.c_str(), TRUE)) return GetLastError();
    CHandle file(CreateFileW(job.installer.c_str(), GENERIC_WRITE, FILE_SHARE_READ,
        nullptr, CREATE_NEW, FILE_ATTRIBUTE_NORMAL, nullptr));
    if (file == INVALID_HANDLE_VALUE) { file.Detach(); return GetLastError(); }
    InternetHandle session(InternetOpenW(L"FileSpacer updater", INTERNET_OPEN_TYPE_PRECONFIG,
        nullptr, nullptr, 0));
    if (!session.value) return GetLastError();
    DWORD timeout = 15000;
    InternetSetOptionW(session.value, INTERNET_OPTION_CONNECT_TIMEOUT, &timeout, sizeof(timeout));
    InternetSetOptionW(session.value, INTERNET_OPTION_SEND_TIMEOUT, &timeout, sizeof(timeout));
    InternetSetOptionW(session.value, INTERNET_OPTION_RECEIVE_TIMEOUT, &timeout, sizeof(timeout));
    const std::wstring url(job.info.installerUrl.begin(), job.info.installerUrl.end());
    InternetHandle connection(InternetOpenUrlW(session.value, url.c_str(), nullptr, 0,
        INTERNET_FLAG_NO_CACHE_WRITE | INTERNET_FLAG_NO_COOKIES | INTERNET_FLAG_RELOAD, 0));
    if (!connection.value) return GetLastError();
    DWORD status = 0, size = sizeof(status);
    if (!HttpQueryInfoW(connection.value, HTTP_QUERY_STATUS_CODE | HTTP_QUERY_FLAG_NUMBER,
            &status, &size, nullptr)) return GetLastError();
    if (status != HTTP_STATUS_OK) return ERROR_HTTP_INVALID_SERVER_RESPONSE;
    Sha256 hash;
    BYTE buffer[65536];
    uint64_t total = 0;
    for (;;) {
        if (job.cancel.load()) return ERROR_CANCELLED;
        DWORD count = 0, written = 0;
        if (!InternetReadFile(connection.value, buffer, sizeof(buffer), &count)) return GetLastError();
        if (!count) break;
        if (total + count > job.info.installerSize) return ERROR_INVALID_DATA;
        if (!WriteFile(file, buffer, count, &written, nullptr)) return GetLastError();
        if (written != count) return ERROR_WRITE_FAULT;
        if (!hash.append(buffer, count)) return ERROR_INVALID_DATA;
        total += count;
        job.received.store(total);
    }
    if (job.cancel.load()) return ERROR_CANCELLED;
    if (total != job.info.installerSize || hash.finish() != job.info.sha256)
        return ERROR_INVALID_DATA;
    return FlushFileBuffers(file) ? ERROR_SUCCESS : GetLastError();
}

DWORD startRelay(UpdateJob &job) {
    // Inherit only the installation gate, never SQLite/recovery handles or locks.
    SIZE_T size = 0;
    InitializeProcThreadAttributeList(nullptr, 1, 0, &size);
    std::vector<BYTE> storage(size);
    auto attributes = reinterpret_cast<LPPROC_THREAD_ATTRIBUTE_LIST>(storage.data());
    if (!InitializeProcThreadAttributeList(attributes, 1, 0, &size)) return GetLastError();
    HANDLE gate = job.gate;
    DWORD error = ERROR_SUCCESS;
    if (!UpdateProcThreadAttribute(attributes, 0, PROC_THREAD_ATTRIBUTE_HANDLE_LIST,
            static_cast<void *>(&gate), sizeof(gate), nullptr, nullptr)) {
        error = GetLastError();
    } else {
        std::wstring command = quoted(job.relay) + L" /update-install " + quoted(job.target)
            + L" " + quoted(job.installer) + L" "
            + std::wstring(job.info.sha256.begin(), job.info.sha256.end()) + L" "
            + std::to_wstring(job.info.installerSize) + L" "
            + std::to_wstring(reinterpret_cast<uintptr_t>(gate));
        STARTUPINFOEXW startup = {};
        startup.StartupInfo.cb = sizeof(startup);
        startup.lpAttributeList = attributes;
        PROCESS_INFORMATION process = {};
        if (!CreateProcessW(job.relay.c_str(), &command[0], nullptr, nullptr, TRUE,
                EXTENDED_STARTUPINFO_PRESENT | CREATE_NO_WINDOW, nullptr,
                job.directory.c_str(), &startup.StartupInfo, &process)) error = GetLastError();
        else {
            CloseHandle(process.hThread);
            CloseHandle(process.hProcess);
            job.handedOff = true;
        }
    }
    DeleteProcThreadAttributeList(attributes);
    return error;
}

struct UpdateControls {
    std::shared_ptr<UpdateJob> job;
    UpdateInfo available;
    bool installing = false;
    bool destroyed = false;
    bool progress = false;
    bool holdsProcessLock = false;
};

void setLabel(HWND page, const wchar_t *text) { SetDlgItemTextW(page, IDC_UPDATE_STATUS, text); }

void readyButton(HWND page, const UpdateControls &controls) {
    if (controls.progress) {
        EnableWindow(GetDlgItem(page, IDCANCEL), !controls.installing);
        if (!controls.job && !controls.installing)
            SetDlgItemTextW(page, IDCANCEL, getString(IDS_UPDATE_CLOSE_BUTTON));
        return;
    }
    if (controls.available.isNewer) {
        const std::string version = releaseVersion(controls.available.version);
        const std::wstring wide(version.begin(), version.end());
        SetDlgItemTextW(page, IDC_UPDATES_LINK,
            formatString(controls.available.installerUrl.empty() ? IDS_UPDATE_RELEASE_BUTTON
                : IDS_UPDATE_INSTALL_BUTTON, wide.c_str()).get());
    } else SetDlgItemTextW(page, IDC_UPDATES_LINK, getString(IDS_UPDATE_SEARCH_BUTTON));
    EnableWindow(GetDlgItem(page, IDC_UPDATES_LINK), !controls.installing);
}

void startJob(HWND page, UpdateControls &controls, bool download) {
    try {
        auto job = std::make_shared<UpdateJob>(download);
        if (download) {
            job->info = controls.available;
            SECURITY_ATTRIBUTES security = {sizeof(security), nullptr, TRUE};
            job->gate.Attach(CreateEventW(&security, TRUE, FALSE, INSTALL_EVENT));
            DWORD error = GetLastError();
            if (!job->gate || error == ERROR_ALREADY_EXISTS) {
                setLabel(page, getString(IDS_UPDATE_BUSY)); return;
            }
        }
        controls.job = job;
        EnableWindow(GetDlgItem(page, IDC_UPDATES_LINK), FALSE);
        setLabel(page, getString(download ? IDS_UPDATE_DOWNLOADING : IDS_UPDATE_SEARCHING));
        // A destroyed page cancels its job. The worker holds only shared data, no HWND.
        lockProcess();
        try {
            std::thread([job]() mutable {
                try {
                    job->error = job->download ? downloadInstaller(*job)
                        : checkUpdate(&job->info, &job->cancel);
                } catch (...) { job->error = ERROR_NOT_ENOUGH_MEMORY; }
                job->done.store(true, std::memory_order_release);
                job.reset(); // Complete cancellation cleanup before releasing the worker lifetime.
                unlockProcess();
            }).detach();
        } catch (...) { unlockProcess(); throw; }
    } catch (...) {
        controls.job.reset();
        setLabel(page, getString(IDS_UPDATE_FAILED));
        readyButton(page, controls);
    }
}

