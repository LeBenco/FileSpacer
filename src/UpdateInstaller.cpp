void initUpdateControls(HWND page) {
    auto holder = std::unique_ptr<std::shared_ptr<UpdateControls>>(
        new (std::nothrow) std::shared_ptr<UpdateControls>());
    if (!holder) { EnableWindow(GetDlgItem(page, IDC_UPDATES_LINK), FALSE); return; }
    try { *holder = std::make_shared<UpdateControls>(); }
    catch (...) { setLabel(page, getString(IDS_UPDATE_FAILED)); return; }
    if (!SetWindowSubclass(page, updateControlsProc, UPDATE_TIMER,
            reinterpret_cast<DWORD_PTR>(holder.get()))) return;
    if (!SetTimer(page, UPDATE_TIMER, 200, nullptr)) {
        RemoveWindowSubclass(page, updateControlsProc, UPDATE_TIMER);
        setLabel(page, getString(IDS_UPDATE_FAILED)); return;
    }
    cleanOldRelays();
    startJob(page, **holder, false);
    (void)holder.release(); // NOLINT(bugprone-unused-return-value) -- Ownership passes to WM_NCDESTROY.
}

bool handleUpdateCommandLine(int argc, wchar_t **argv, int *exitCode) {
    if (argc < 2 || lstrcmpiW(argv[1], L"/update-install") != 0) return false;
    DWORD error;
    try { error = runInstallerRelay(argc, argv); }
    catch (...) { error = ERROR_NOT_ENOUGH_MEMORY; }
    if (error) MessageBoxW(nullptr,
        formatString(IDS_UPDATE_RELAY_FAILED, getErrorMessage(error).get()).get(),
        getString(IDS_APP_NAME), MB_OK | MB_ICONERROR);
    *exitCode = error ? 1 : 0;
    return true;
}

bool isUpdateInstallationRunning() {
    CHandle gate(OpenEventW(SYNCHRONIZE, FALSE, INSTALL_EVENT));
    return gate && WaitForSingleObject(gate, 0) == WAIT_OBJECT_0;
}

bool handleUpdateDialogMessage(MSG *message) {
    return progressDialog && IsDialogMessageW(progressDialog, message);
}

void closeUpdateDialogs() {
    if (progressDialog) DestroyWindow(progressDialog);
}

